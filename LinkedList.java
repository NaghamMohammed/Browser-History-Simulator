public class LinkedList {

    private Node head;  // يشير لاول نود
    private Node tail;  // يشير لاخر نود وهي التوب تقريبا
    // كونستركتور الكلاس الذي يهيئ المتغيرات
    public LinkedList(){
        this.head=null;
        this.tail=null;
    }
    public boolean isEmpty(){
        return head==null;
    }
    //ميثود الاضافة 
    //نحن نريد اضافة نود اذا يجب ان انشئ النود اولا
    //اذا كانت فارغة ؟ يبقى الهيد والتيل والنود الجديدة واحد لانها حتكون الاولى والاخيرة 
    //اذا لم تكن فارغة ؟ نربط العقدة الجديدة باخر عقدة يشير لها التيل 
    //نحدث التيل بيشير على العقدة الجديدة
    public void addLast(String url){
        Node newNode = new Node(url);
        if(isEmpty()){
            head = newNode;
            tail= newNode;
        }else{
            tail.setNext(newNode);
            tail=newNode;


        }
    }
    // ميثودعرض محتويات القائمة :
    // اذا كانت فارغة ؟ رح اظهر رسالة تخبر ان الليست فارغة 
    //اذا لم تكن فارغة ؟ نحتاج متغير يحفظ القيم ويبدا من الهيد 
    //نطبع الهيد
    //ننتقل الى العقدة التالية 
    //شرط التوقف هو ان يصل المتغير الذي يخزن القيم الى النهاية يشير الى null
    public  void display(){
        if(isEmpty()){
            System.out.println("Browsing history is empty");
            return ;
        }
        Node cuurent= head;
        while (cuurent!= null) {
            System.out.println(cuurent.getUrl());
            cuurent = cuurent.getNext();
        }
    }
    // بدي اجيب عدد عناصر القائمة بطريقة الاستدعاء الذاتي 
    // عندي دالتين : دالة عامة(يقوم المستخدم باستدعائها )و بتستدعي دالة خاصة تقوم بالعد على كل عقدة في القائمة  والتي تحدد كيف ننتقل للعقدة التالية و متى نتوقف عن العد
    public  int count(){ // 
        return countNodes(head);//استدعاء ذاتي للميثود فقمت باستدعاء الدالة الثانية ومررت لها الهيد  لاننا نريد ان يبدا العد من اول نود في القائمة ونعطيه لل الموقع الحالي في القائمة
    }
    private  int countNodes(Node current){// هذه الدالة تستقبل نود اسمها كارنت لاننا نريد الانتقال للعقدة التالية دون ان نغير قيمة الهيد
        if(current==null){ //هذا الشرط الذي يوقف عنده الاستدعاء الذاتي وهو عندما يصل الى نهاية القائمة ويكون المؤشر على null
            return 0;//اذا وصلنا الى نهاية القائمة نرجع صفر
        }

        //  احسب العقدة الحالية باضافة 1
        //انتقل الى العقدة التالية بتمرير المؤشر الى العقدة التالية
        //استدعي الدالة مرةاخرى حتى نكمل العد على كل العقد في القائمة
        //انتهينا من العد على العقدة الحالية و انتقلنا الى العقدة التالية و استدعينا الدالة مرة اخرى و هيك نكمل العد على كل العقد في القائمة
        return 1+ countNodes(current.getNext());//هذه عملية العد نفسها حيث نرجع 1+ استدعاء ذاتي للميثود نفسها مع تمرير العقدة التالية 
    }
}
public class Stack {
    private  Node top;  // كل ستاك بالدنيا الها مؤشر اسمه توب باشر على المكان الحالي الاحدث والاخير 
    // طبعا بما انه كل كلاس اله كونستركتور لتهيئة متغيرات كلاسه وتخزين او اعطاء قيم اولية اعطينا المؤشر قيمة فارغة 
    public Stack(){
        top=null;
    }
    // بما انا كلاس الستاك عبارة عن مجموعة من الميثود 
    // فهنا ميثود بتفحص هل الستاك فارغ ؟ 
    // اذا كان التوب فارغ بتردع ترو 
    // اذا كان يختوي عنصر بترجع فولس 
    public boolean isEmpty(){
        return top==null;
    }
    // ميثود الاضافة  
    //اول خطوة للاضافة هي انشاء نود جديد واعطاءها متغيرها المطلوب وهو عنوان الرابط 
    //الان تخديد الاماكن والمشؤرات : نجعل العقدة الجديدة تؤشر على توب القديم
    //الان تحدث التوب القديم ليؤشر على النود الجديدة
    public void push(String url){
        Node newNode = new Node(url);
        newNode.setNext(top);
        top = newNode;     
    }
    // ميثود الحذف 
    //نفحص هل الستاك فارغ ؟ نرجع فارغ واذا لم يكن فارغ ننتقل للخطوة التالية 
    // عملية الحذف خطوتين 
    // نحفظ الرابط الي بالتوب بمتغير عنوان الرابط عشان اقدر ارجعها 
    //نحرك التوب ونعطيه النود التالية وهيك حذفت 
    //نرجع قيمة العقدة الي حذفناها
    public String pop(){
        if(isEmpty()){
            return null;
        }
        String url = top.getUrl();
        top = top.getNext();
        return url;
    }
    // ميثود ارجاع قيمة التوب 
    //  نفحص هل الستاك فارغة ؟اذا اه بنرجع فارغ و اذا لا  ننتقل للخطوة الارجاع
    //بجيب العنوان من التوب وبرجع قيمته
    public String peek(){
        if(isEmpty()){
            return null;
        }
        return top.getUrl();
    }
    
}
